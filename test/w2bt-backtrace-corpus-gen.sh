#!/bin/bash
# usage: w2bt-backtrace-corpus-gen.sh OUT.el  -- build the bytecode corpus with GNU Emacs.
here=$(cd "$(dirname "$0")" && pwd)
out=${1:?out}
ulimit -v 8388608
timeout 300 /usr/local/bin/emacs --batch -Q --eval "
(progn
  (setq lexical-binding t print-length nil print-level nil)
  (let ((forms nil) (names nil))
    (with-temp-buffer
      (insert-file-contents \"$here/w2bt-backtrace-corpus-src.el\")
      (goto-char (point-min))
      (condition-case nil
          (while t (push (read (current-buffer)) forms))
        (end-of-file nil)))
    (setq forms (nreverse forms))
    (with-temp-file \"$out\"
      (insert \";;; -*- lexical-binding: t; -*-\n;; generated by w2bt-backtrace-corpus-gen.sh\n\")
      (dolist (f forms)
        (cond ((eq (car f) 'defvar) (prin1 f (current-buffer)) (insert \"\n\"))
              ((eq (car f) 'defun)
               (let ((fn (byte-compile (eval \`(lambda ,(nth 2 f) ,@(nthcdr 3 f)) t))))
                 (insert (format \"(fset '%s %S)\n\" (nth 1 f) fn))))))
      (insert-file-contents \"$here/w2bt-backtrace-corpus-run.el\" nil)
      (goto-char (point-max)))))" 
