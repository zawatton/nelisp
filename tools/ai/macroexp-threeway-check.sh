#!/usr/bin/env bash
# macroexp-threeway-check.sh --- one entry point for the 3-way macroexpand-all
# measurement: GNU native vs GNU forced-bytecode vs NeLisp forced-bytecode,
# all running the same GNU-compiled tools/ai/macroexp-threeway-driver.el and
# the same macroexp.elc.  Measurement scaffolding only (no runtime change).
#
# Usage: tools/ai/macroexp-threeway-check.sh MODE
#   setup        compile driver + macroexp.el into $MEXP_OUT, run a tiny
#                plain width32 N2 case on all three engines (identical result
#                tokens required) and two wrong-kind controls; on success write
#                $MEXP_OUT/setup-check.log.  Refuses to overwrite a prepared
#                $MEXP_OUT unless MEXP_FORCE_SETUP=1.
#   plain|macros|state|conditional
#                run tools/ai/macroexp-paired-win32.py over the three engines
#                (Windows only).  Output: bench-$tag/ and bench-$tag.log.
#   first-state|first-conditional
#                seven fresh single-pass expansion samples per engine.
#   bad-result-first
#                wrong-result control for the single-pass runner mode.
#   bad-result   integration control: two GNU-bytecode engines, one with
#                BENCH_BAD_RESULT=1; the runner must exit 3 with "result
#                mismatch" and write no report.json; then write
#                $MEXP_OUT/bad-result-check.log.
#
# Environment (no machine defaults; engines are never guessed):
#   NDTW_EMACS_BIN      GNU Emacs (setup, all modes)
#   NDTW_BASELINE_BIN   NeLisp standalone binary (setup, case modes)
#   NDTW_PYTHON_BIN     Python 3 (case modes, bad-result)
#   NDTW_NOTES_ROOT     Notes root holding bin/windows-process-job.py (runner)
#   NDTW_ROOT           game repository root (state / conditional)
#   MEXP_OUT            default <repo>/target/ai/macroexp-threeway
#   MEXP_TAG            run tag, default = case name (bad-result: bad-result)
#   MEXP_LOW/MEXP_HIGH  default 2/10 (bad-result: 2/4); real corpora: 1/2
#   MEXP_REPS (7)  MEXP_CPU (0)  MEXP_WIDTH (optional, passed to the driver)
# Every engine run and the Python runner is wrapped in
# `flock /tmp/notes-heavy.lock timeout N` (queue time is outside the budget).
# Existing outputs are never removed: stale JSON/logs make the script refuse.
# Printed digests are observations, not proof of semantic equivalence.

set -eu
export PATH="/usr/bin:$PATH"
ulimit -v 8388608 || { echo "macroexp-threeway-check: cannot set ulimit -v" >&2; exit 2; }

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
REPO=$(cd "$SCRIPT_DIR/../.." && pwd)
OUT=${MEXP_OUT:-$REPO/target/ai/macroexp-threeway}
# These values cross into native Windows processes as environment variables.
if command -v cygpath >/dev/null 2>&1; then
    REPO=$(cygpath -m "$REPO")
    OUT=$(cygpath -m "$OUT")
fi
LOCK=/tmp/notes-heavy.lock
DRIVER_EL=$REPO/tools/ai/macroexp-threeway-driver.el
RUNNER=$REPO/tools/ai/macroexp-paired-win32.py
PROVIDER_SRC=$REPO/vendor/staged-emacs-lisp/macroexp.el
DRIVER_ELC=$OUT/macroexp-threeway-driver.elc
PROVIDER_ELC=$OUT/macroexp.elc

die() { echo "macroexp-threeway-check: $*" >&2; exit 2; }
need_env() { for v in "$@"; do eval "val=\${$v:-}"; [ -n "$val" ] || die "$v must be set"; done; }
need_exec() { [ -x "$(command -v "$1" 2>/dev/null || true)" ] || [ -x "$1" ] || die "not executable: $1"; }

# GNU Emacs on Windows wants TEMP/TMP; derive them only from existing settings.
if [ -z "${TEMP:-}" ] && [ -n "${TMPDIR:-}" ]; then export TEMP=$TMPDIR; fi
if [ -z "${TMP:-}" ] && [ -n "${TEMP:-}" ]; then export TMP=$TEMP; fi
if [ -z "${TEMP:-}" ] && [ -n "${TMP:-}" ]; then export TEMP=$TMP; fi

usage() { sed -n '2,/^set -eu/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//' >&2; exit 2; }

# One engine run; caller exports MEXP_* first.  Usage: run_engine ENGINE OUT ERR
# ENGINE is nelisp (NDTW_BASELINE_BIN --load) or anything else (GNU batch).
run_engine() {
    local engine=$1 so=$2 se=$3
    if [ "$engine" = nelisp ]; then
        flock "$LOCK" timeout 60 "$NDTW_BASELINE_BIN" --load "$DRIVER_ELC" >"$so" 2>"$se"
    else
        flock "$LOCK" timeout 60 "$NDTW_EMACS_BIN" -Q --batch -l "$DRIVER_ELC" >"$so" 2>"$se"
    fi
}

mode_setup() {
    need_env NDTW_EMACS_BIN NDTW_BASELINE_BIN
    need_exec "$NDTW_EMACS_BIN"; need_exec "$NDTW_BASELINE_BIN"
    [ -f "${NDTW_BASELINE_BIN}.native-startup.el" ] || die "incomplete NeLisp deployment: native-startup companion missing"
    [ -f "$DRIVER_EL" ] || die "missing $DRIVER_EL"
    [ -f "$PROVIDER_SRC" ] || die "missing $PROVIDER_SRC"
    if [ "${MEXP_FORCE_SETUP:-0}" != 1 ]; then
        for f in "$DRIVER_ELC" "$PROVIDER_ELC" "$OUT/setup-check.log"; do
            [ ! -e "$f" ] || die "$f exists; setup would overwrite prepared artifacts (MEXP_FORCE_SETUP=1 to force)"
        done
    fi
    mkdir -p "$OUT"
    cat > "$OUT/prepare.el" <<'EOF'
;;; prepare.el --- generated by macroexp-threeway-check.sh -*- lexical-binding: t; -*-
(let* ((repo (getenv "MEXP_REPO"))
       (out (getenv "MEXP_OUT"))
       (provider (expand-file-name "macroexp.el" out))
       (driver (expand-file-name "macroexp-threeway-driver.el" out)))
  (copy-file (expand-file-name "vendor/staged-emacs-lisp/macroexp.el" repo) provider t)
  (copy-file (expand-file-name "tools/ai/macroexp-threeway-driver.el" repo) driver t)
  (dolist (file (list provider driver))
    (unless (byte-compile-file file) (error "Compilation failed: %s" file)))
  (princ "MEXP-PREPARE-PASS\n"))
EOF
    echo "setup: compiling into $OUT"
    local rc=0
    ( export MEXP_REPO="$REPO" MEXP_OUT="$OUT"
      flock "$LOCK" timeout 90 "$NDTW_EMACS_BIN" -Q --batch -l "$OUT/prepare.el" > "$OUT/prepare.log" 2>&1 ) || rc=$?
    [ "$rc" -eq 0 ] || { tail -n 8 "$OUT/prepare.log" >&2; die "prepare failed (exit $rc), see $OUT/prepare.log"; }
    grep -q 'MEXP-PREPARE-PASS' "$OUT/prepare.log" || die "prepare did not report pass, see $OUT/prepare.log"
    [ -f "$DRIVER_ELC" ] && [ -f "$PROVIDER_ELC" ] || die "compiled artifacts missing in $OUT"

    # Positive: tiny plain case on three engines, identical result tokens.
    local engine mode so se meta line first_token="" token
    for engine in gnu_native gnu_bc nelisp; do
        mode=bytecode; [ "$engine" = gnu_native ] && mode=native
        so=$OUT/setup-$engine.stdout; se=$OUT/setup-$engine.stderr; meta=$OUT/setup-meta-$engine
        mkdir -p "$meta"
        rc=0
        ( export MEXP_MODE=$mode MEXP_CASE=plain BENCH_N=2 MEXP_WIDTH=32 \
                 MEXP_SAMPLE_ID="setup-$engine" \
                 MEXP_PROVIDER="$PROVIDER_ELC" MEXP_META_DIR="$meta"
          unset MEXP_BAD_KIND BENCH_BAD_RESULT
          run_engine "$engine" "$so" "$se" ) || rc=$?
        [ "$rc" -eq 0 ] || die "$engine exited $rc; see $se and $meta"
        [ "$(tr -d '\r' < "$so" | wc -l)" -eq 1 ] || die "$engine stdout is not exactly one line: $so"
        line=$(tr -d '\r' < "$so")
        printf '%s\n' "$line" | grep -Eq '^BENCH-CHECK n=2 result=[^ ]+ elapsed=[0-9.]+$' \
            || die "$engine stdout is not a single BENCH-CHECK line: $so"
        token=$(printf '%s\n' "$line" | sed 's/^BENCH-CHECK n=2 result=\([^ ]*\) elapsed=.*/\1/')
        echo "setup: $engine token=$token"
        if [ -z "$first_token" ]; then first_token=$token
        elif [ "$token" != "$first_token" ]; then die "$engine result token $token differs from $first_token"
        fi
    done

    # Negative: wrong-kind controls must exit 1, print nothing, and say why.
    for engine in gnu_native nelisp; do
        mode=bytecode; [ "$engine" = gnu_native ] && mode=native
        so=$OUT/negative-$engine.stdout; se=$OUT/negative-$engine.stderr; meta=$OUT/negative-meta-$engine
        mkdir -p "$meta"
        rc=0
        ( export MEXP_MODE=$mode MEXP_CASE=plain BENCH_N=2 MEXP_WIDTH=32 MEXP_BAD_KIND=1 \
                 MEXP_SAMPLE_ID="negative-$engine" \
                 MEXP_PROVIDER="$PROVIDER_ELC" MEXP_META_DIR="$meta"
          unset BENCH_BAD_RESULT
          run_engine "$engine" "$so" "$se" ) || rc=$?
        [ "$rc" -eq 1 ] || die "wrong-kind control $engine exited $rc (expected 1); see $se"
        [ ! -s "$so" ] || die "wrong-kind control $engine wrote stdout: $so"
        if ! cat "$meta"/*.log 2>/dev/null | grep -q 'MEXP-ERROR.*kind mismatch'; then
            die "wrong-kind control $engine metadata lacks MEXP-ERROR kind mismatch: $meta"
        fi
        echo "setup: wrong-kind control $engine ok (exit 1, empty stdout, kind mismatch)"
    done
    printf 'MEXP-SETUP-PASS three engines token=%s and two wrong-kind controls\n' "$first_token" \
        > "$OUT/setup-check.log"
    cat "$OUT/setup-check.log"
}

# Common runner preconditions.
runner_preflight() {
    need_env NDTW_EMACS_BIN NDTW_PYTHON_BIN NDTW_NOTES_ROOT
    need_exec "$NDTW_EMACS_BIN"; need_exec "$NDTW_PYTHON_BIN"
    [ -f "$RUNNER" ] || die "missing $RUNNER"
    [ -f "$DRIVER_ELC" ] && [ -f "$PROVIDER_ELC" ] || die "run '$0 setup' first (missing compiled artifacts in $OUT)"
    export NDTW_NOTES_ROOT
}

# Refuse stale results for TAG instead of deleting them.
refuse_stale() {
    local tag=$1
    for f in "$OUT/bench-$tag/raw.json" "$OUT/bench-$tag/report.json" "$OUT/bench-$tag.log"; do
        [ ! -e "$f" ] || die "stale output $f; choose a new MEXP_TAG (outputs are never removed)"
    done
}

mode_case() {
    local kind=$1 tag=${MEXP_TAG:-$1} rc=0
    local count_args=()
    case "$kind" in
        first-*) kind=${kind#first-}; count_args=(--single-pass) ;;
        *) count_args=(--low "${MEXP_LOW:-2}" --high "${MEXP_HIGH:-10}") ;;
    esac
    need_env NDTW_BASELINE_BIN; need_exec "$NDTW_BASELINE_BIN"
    [ -f "${NDTW_BASELINE_BIN}.native-startup.el" ] || die "incomplete NeLisp deployment: native-startup companion missing"
    runner_preflight
    case $kind in state|conditional) need_env NDTW_ROOT; export NDTW_ROOT ;; esac
    refuse_stale "$tag"
    local meta=$OUT/meta-$tag
    mkdir -p "$meta"
    (
        export MEXP_CASE=$kind MEXP_PROVIDER="$PROVIDER_ELC" MEXP_MODE=native MEXP_META_DIR="$meta"
        unset MEXP_BAD_KIND BENCH_BAD_RESULT
        flock "$LOCK" timeout 600 "$NDTW_PYTHON_BIN" "$RUNNER" \
            --engine "gnu_native=$NDTW_EMACS_BIN" \
            --engine "gnu_bc=$NDTW_EMACS_BIN" \
            --engine "nelisp=$NDTW_BASELINE_BIN" \
            --engine-env gnu_bc=MEXP_MODE=bytecode \
            --engine-env nelisp=MEXP_MODE=bytecode \
            --driver "$DRIVER_ELC" \
            "${count_args[@]}" \
            --cpu "${MEXP_CPU:-0}" --reps "${MEXP_REPS:-7}" --timeout 580 --allow-busy \
            --out "$OUT/bench-$tag" > "$OUT/bench-$tag.log" 2>&1
    ) || rc=$?
    cat "$OUT/bench-$tag.log"
    if [ "$rc" -ne 0 ]; then
        echo "macroexp-threeway-check: $kind run FAILED (exit $rc); raw: $OUT/bench-$tag/raw.json" >&2
        exit "$rc"
    fi
}

mode_bad_result() {
    local tag=${MEXP_TAG:-${1:-bad-result}} rc=0
    local count_args=()
    if [ "${1:-bad-result}" = bad-result-first ]; then
        count_args=(--single-pass)
    else
        count_args=(--low "${MEXP_LOW:-2}" --high "${MEXP_HIGH:-4}")
    fi
    runner_preflight
    refuse_stale "$tag"
    local meta=$OUT/meta-$tag
    mkdir -p "$meta"
    (
        export MEXP_CASE=plain MEXP_WIDTH=32 MEXP_PROVIDER="$PROVIDER_ELC" MEXP_MODE=bytecode MEXP_META_DIR="$meta"
        unset MEXP_BAD_KIND BENCH_BAD_RESULT
        flock "$LOCK" timeout 600 "$NDTW_PYTHON_BIN" "$RUNNER" \
            --engine "base=$NDTW_EMACS_BIN" \
            --engine "bad=$NDTW_EMACS_BIN" \
            --engine-env base=MEXP_MODE=bytecode \
            --engine-env bad=MEXP_MODE=bytecode \
            --engine-env bad=BENCH_BAD_RESULT=1 \
            --driver "$DRIVER_ELC" \
            "${count_args[@]}" \
            --cpu "${MEXP_CPU:-0}" --reps "${MEXP_REPS:-1}" --timeout 580 --allow-busy \
            --out "$OUT/bench-$tag" > "$OUT/bench-$tag.log" 2>&1
    ) || rc=$?
    cat "$OUT/bench-$tag.log"
    [ "$rc" -eq 3 ] || die "bad-result control: runner exited $rc, expected 3; see $OUT/bench-$tag.log"
    grep -q 'result mismatch' "$OUT/bench-$tag.log" || die "bad-result control: no 'result mismatch' in $OUT/bench-$tag.log"
    [ ! -e "$OUT/bench-$tag/report.json" ] || die "bad-result control: report.json was written"
    printf 'MEXP-BAD-RESULT-PASS runner exit 3, result mismatch, no report.json (tag %s)\n' "$tag" \
        > "$OUT/$tag-check.log"
    cat "$OUT/$tag-check.log"
}

case "${1:-}" in
    setup) mode_setup ;;
    plain|macros|state|conditional|first-state|first-conditional) mode_case "$1" ;;
    bad-result|bad-result-first) mode_bad_result "$1" ;;
    *) usage ;;
esac
