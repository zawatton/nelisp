// Genuine rootstack functions execute in one Wasm memory; JS supplies assertions.
import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';

const path = process.argv[2] || 'target/wasm-rootstack/fixture.wasm';
const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const manifest = JSON.parse(fs.readFileSync(`${path}.json`, 'utf8'));
assert.equal(manifest.schema_version, 1);
assert.equal(hash(path), manifest.wasm_sha256, 'module identity');
for (const [file, expected] of manifest.source_sha256) assert.equal(hash(file), expected, file);
assert.deepEqual(manifest.genuine_functions,
  ['nl_rootstack_init', 'nl_root_depth', 'nl_rootstack_end', 'nl_root_reserve_slot']);
assert.equal(manifest.region_bytes, 131072 * 32);
const bytes = fs.readFileSync(path);
assert(WebAssembly.validate(bytes));
const module = new WebAssembly.Module(bytes);
assert.equal(WebAssembly.Module.imports(module).length, 0);
assert.equal(WebAssembly.Module.exports(module).filter(row => row.kind === 'memory').length, 1);
assert.equal(WebAssembly.Module.exports(module).filter(row => row.kind === 'function').length, 8);
const create = () => new WebAssembly.Instance(module, {}).exports;
const runtime = create();
assert(runtime.memory.buffer instanceof ArrayBuffer);
assert(!(runtime.memory.buffer instanceof SharedArrayBuffer));
const view = new DataView(runtime.memory.buffer);
let checked = 0;
const equal = (actual, expected, label) => { assert.equal(actual, expected, label); checked++; };
const top = runtime['rootstack-top-address']();
const region = runtime['rootstack-region-address']();
const end = runtime.nl_rootstack_end();
equal(top, BigInt(manifest.top), 'owned top address');
equal(region, BigInt(manifest.region), 'owned region address');
equal(region, top + 8n, 'disjoint aligned owners');
equal(top > 0n && top % 8n === 0n && region % 8n === 0n, true, 'nonzero aligned storage');
equal(end, region + 4194304n, 'genuine capacity');
equal(view.getBigUint64(Number(top), true), 0n, 'zero BSS top');
equal(new Uint8Array(runtime.memory.buffer, Number(region), 4194304).every(byte => byte === 0), true, 'zero BSS region');
equal(runtime.nl_root_depth(), 0n, 'uninitialized depth');
runtime.nl_rootstack_init();
equal(runtime.nl_root_depth(), 0n, 'initialized depth');
equal(view.getBigUint64(Number(top), true), region, 'initialized top');
for (let i = 0; i < 4; i++) view.setBigUint64(Number(region) + 8 * i, BigInt(100 + i), true);
new Uint8Array(runtime.memory.buffer, Number(region + 32n), 32).fill(0x5a);
equal(runtime.nl_root_reserve_slot(region), region, 'first reservation');
for (let i = 0; i < 4; i++) equal(view.getBigUint64(Number(region) + 8 * i, true), 0n, `cleared word${i}`);
equal(view.getBigUint64(Number(top), true), region + 32n, 'top advanced32');
equal(runtime.nl_root_depth(), 1n, 'depth1');
equal(new Uint8Array(runtime.memory.buffer, Number(region + 32n), 32).every(byte => byte === 0x5a), true, 'next slot intact');
view.setBigUint64(Number(region), 123n, true);
runtime.nl_rootstack_init();
equal(view.getBigUint64(Number(top), true), region + 32n, 'repeat init preserves top');
equal(view.getBigUint64(Number(region), true), 123n, 'repeat init preserves active root');
equal(runtime.nl_root_depth(), 1n, 'repeat init preserves depth');
const last = end - 32n;
for (let i = 0; i < 4; i++) view.setBigUint64(Number(last) + 8 * i, BigInt(200 + i), true);
new Uint8Array(runtime.memory.buffer, Number(end), 32).fill(0xa5);
equal(runtime.nl_root_reserve_slot(last), last, 'last valid slot');
for (let i = 0; i < 4; i++) equal(view.getBigUint64(Number(last) + 8 * i, true), 0n, `last cleared word${i}`);
equal(view.getBigUint64(Number(top), true), end, 'top at capacity');
equal(runtime.nl_root_depth(), 131072n, 'depth at capacity');
equal(runtime.nl_root_reserve_slot(end), 0n, 'capacity overflow refuses');
equal(view.getBigUint64(Number(top), true), end, 'overflow preserves top');
equal(new Uint8Array(runtime.memory.buffer, Number(end), 32).every(byte => byte === 0xa5), true, 'adjacent memory intact');
equal(view.getBigUint64(Number(region), true), 123n, 'overflow preserves existing roots');
equal(runtime.nl_root_reserve_slot(0n), 0n, 'null reservation refuses');
equal(view.getBigUint64(Number(top), true), end, 'null preserves top');
equal(runtime['managed-cursor-probe'](), BigInt(manifest.managed_cursor), 'managed cursor after static storage');
equal(BigInt(manifest.managed_cursor) >= end, true, 'managed allocation disjoint from rootstack');
equal(runtime['managed-cursor-probe'](), BigInt(manifest.managed_cursor) + 8n, 'managed cursor advances separately');
equal(runtime['literal-address-word'](), 268435544n, 'ordinary scalar remains literal');
const other = create();
equal(other.memory.buffer !== runtime.memory.buffer, true, 'independent memory instance');
const otherView = new DataView(other.memory.buffer);
equal(other.nl_root_depth(), 0n, 'second instance depth0');
equal(otherView.getBigUint64(Number(top), true), 0n, 'second instance top zero');
other.nl_rootstack_init();
equal(otherView.getBigUint64(Number(top), true), region, 'second instance initializes itself');
equal(otherView.getBigUint64(Number(region), true), 0n, 'second instance roots zero');
equal(runtime.nl_root_depth(), 131072n, 'first instance remains at capacity');
equal(other.nl_root_reserve_slot(region), region, 'second instance reserves separately');
equal(other.nl_root_depth(), 1n, 'second instance depth1');
equal(view.getBigUint64(Number(top), true), end, 'second instance cannot change first top');
assert(checked >= 40, 'all fixed lifecycle assertions executed');
console.log(`GATE-COUNT checked=${checked} findings=0`);
