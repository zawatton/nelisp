#!/usr/bin/env python3
"""compall-idcheck.py DATA_FILE: the native row table is the generated one (exit 0 = pass).
Checks: the file says it is generated by tools/ai/compall-gen.el; every row id is BASE plus the
row's rank (ids consecutive from BASE in file order); the names are in string< order (so the id
is the rank of the sorted name, not assigned by hand); no name twice; at least 300 rows."""
import re, sys
s = open(sys.argv[1], encoding='utf-8').read()
if 'GENERATED by tools/ai/compall-gen.el' not in s: sys.exit('not generated by compall-gen')
m = re.search(r'Ids are (\d+) plus the rank', s)
if not m: sys.exit('no id base stated')
base = int(m.group(1))
rows = re.findall(r"^(?:    \(|  '\(\()((?:\\.|[^\s()\\])+) (\d+) ", s, re.M)
names = [re.sub(r'\\(.)', r'\1', n) for n, _ in rows]
ids = [int(i) for _, i in rows]
bad = [(n, i, base + k) for k, (n, i) in enumerate(zip(names, ids)) if i != base + k]
if bad: sys.exit(f'id not base+rank: {bad[:5]}')
if names != sorted(names): sys.exit('names not in sorted order')
if len(set(names)) != len(names): sys.exit('duplicate name')
if len(rows) < 300: sys.exit(f'only {len(rows)} rows')
print(f'compall-idcheck: rows={len(rows)} base={base} ok')
