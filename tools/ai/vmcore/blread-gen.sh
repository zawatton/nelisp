#!/bin/sh
# Usage: blread-gen.sh OUT.el -- byte-compile blread-src.el with GNU Emacs and append the driver.
d=$(dirname "$0")
emacs -Q --batch --eval '
(progn
  (setq print-escape-newlines t print-escape-control-characters t print-escape-nonascii t print-escape-multibyte t print-length nil print-level nil)
  (let ((forms nil))
    (with-temp-buffer
      (insert-file-contents (expand-file-name "blread-src.el" (file-name-directory (or load-file-name (car command-line-args-left) "."))))
      (goto-char (point-min))
      (condition-case nil (while t (push (read (current-buffer)) forms)) (end-of-file nil)))
    (setq forms (nreverse forms))
    (with-temp-file (car (last command-line-args))
      (insert ";; -*- lexical-binding: t -*-\n;; generated by blread-gen.sh\n")
      (dolist (f forms)
        (if (eq (car f) (quote defun))
            (progn (eval f t) (byte-compile (cadr f))
                   (prin1 (list (quote fset) (list (quote quote) (cadr f)) (symbol-function (cadr f))) (current-buffer)))
          (eval f t) (prin1 f (current-buffer)))
        (insert "\n"))))) ' "$d/blread-src.el" "$1"
