"""Keep tools/ai/reprs/case-overlay.el equal to `nelisp--case-string-fast' in the prelude.
The overlay is a verification aid: the lane's two builds were spent before this last prelude-only
change (a full-mapping branch in the case fast path), so the S2/S4 case checks load it over the build.
Usage: case-overlay-check.py [--write]   exit 0 iff the overlay text equals the prelude's definition."""
import pathlib, re, sys
root = pathlib.Path(__file__).resolve().parents[3]
src = (root / 'scripts/nelisp-stdlib-prelude.el').read_text()
m = re.search(r'^\(defun nelisp--case-string-fast ', src, re.M)
form = src[m.start():src.index('\n(', m.end()) + 1].rstrip() + '\n'
out = root / 'tools/ai/reprs/case-overlay.el'
if '--write' in sys.argv:
    out.write_text(';;; -*- lexical-binding: t; -*-\n;; Generated by case-overlay-check.py --write from scripts/nelisp-stdlib-prelude.el.\n' + form)
ok = out.exists() and out.read_text().endswith(form)
print('overlay equals the prelude definition' if ok else 'overlay differs from the prelude definition')
sys.exit(0 if ok else 1)
